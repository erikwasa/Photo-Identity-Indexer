namespace PhotoIdentity.Persistence.Postgres;

/// <summary>
/// WI-0155 v46: a human-approved link between one reviewed face and a video
/// presence *action*. Links are auditable, reversible and source-exclusion
/// scoped. The ordinary manual video-person history remains authoritative.
/// </summary>
public sealed partial class PostgresCatalogueDatabase
{
    private const string VideoFacePresenceSchemaMigration = """
        CREATE TABLE video_face_presence_actions (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            asset_revision_id uuid NOT NULL,
            media_kind text NOT NULL DEFAULT 'video' CHECK (media_kind='video'),
            observation_id uuid NOT NULL REFERENCES video_face_observations(id) ON DELETE CASCADE,
            person_id uuid NOT NULL REFERENCES people(id) ON DELETE RESTRICT,
            review_action_id bigint NOT NULL REFERENCES video_face_review_actions(id) ON DELETE CASCADE,
            add_action_id bigint NOT NULL REFERENCES video_person_actions(id) ON DELETE CASCADE,
            remove_action_id bigint NULL REFERENCES video_person_actions(id) ON DELETE SET NULL,
            action_kind text NOT NULL CHECK (action_kind IN ('link', 'unlink')),
            actor text NOT NULL CHECK (char_length(btrim(actor)) BETWEEN 1 AND 120),
            created_at_utc timestamptz NOT NULL,
            CONSTRAINT fk_video_face_presence_revision
                FOREIGN KEY (asset_revision_id, media_kind)
                REFERENCES asset_revisions (id, media_kind) ON DELETE CASCADE,
            CONSTRAINT ck_video_face_presence_action
                CHECK (action_kind <> 'link' OR remove_action_id IS NULL)
        );
        CREATE INDEX ix_video_face_presence_observation_latest
            ON video_face_presence_actions(observation_id, id DESC);
        CREATE INDEX ix_video_face_presence_revision_person
            ON video_face_presence_actions(asset_revision_id, person_id, id DESC);
        """;
}
