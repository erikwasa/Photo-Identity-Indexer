namespace PhotoIdentity.Persistence.Postgres;

/// <summary>
/// WI-0155: production video-face review storage. Face observations are derived,
/// revision-bound evidence, never photo face occurrences or automatic video tags.
/// A source exclusion purges the complete batch, including decisions, atomically.
/// </summary>
public sealed partial class PostgresCatalogueDatabase
{
    private const string VideoFaceReviewSchemaMigration = """
        CREATE TABLE video_face_evidence_batches (
            id uuid NOT NULL PRIMARY KEY,
            asset_revision_id uuid NOT NULL,
            media_kind text NOT NULL DEFAULT 'video' CHECK (media_kind='video'),
            source_sha256 text NOT NULL CHECK (source_sha256 ~ '^[0-9a-f]{64}$'),
            producer_version text NOT NULL CHECK (char_length(btrim(producer_version)) BETWEEN 1 AND 100),
            detector_model_id text NOT NULL CHECK (char_length(btrim(detector_model_id)) BETWEEN 1 AND 100),
            detector_model_hash text NOT NULL CHECK (detector_model_hash ~ '^[0-9a-f]{64}$'),
            sface_model_id text NOT NULL CHECK (char_length(btrim(sface_model_id)) BETWEEN 1 AND 100),
            sface_model_hash text NOT NULL CHECK (sface_model_hash ~ '^[0-9a-f]{64}$'),
            alignment_protocol text NOT NULL CHECK (char_length(btrim(alignment_protocol)) BETWEEN 1 AND 100),
            observation_count integer NOT NULL CHECK (observation_count BETWEEN 1 AND 256),
            created_at_utc timestamptz NOT NULL,
            CONSTRAINT fk_video_face_batch_revision FOREIGN KEY (asset_revision_id, media_kind)
                REFERENCES asset_revisions (id, media_kind) ON DELETE CASCADE,
            CONSTRAINT ux_video_face_batch_revision UNIQUE (asset_revision_id)
        );
        CREATE INDEX ix_video_face_batch_revision ON video_face_evidence_batches(asset_revision_id);

        CREATE TABLE video_face_observations (
            id uuid NOT NULL PRIMARY KEY,
            batch_id uuid NOT NULL REFERENCES video_face_evidence_batches (id) ON DELETE CASCADE,
            frame_ordinal integer NOT NULL CHECK (frame_ordinal BETWEEN 0 AND 127),
            timestamp_ms bigint NOT NULL CHECK (timestamp_ms BETWEEN 0 AND 86400000),
            face_ordinal integer NOT NULL CHECK (face_ordinal BETWEEN 0 AND 31),
            frame_width integer NOT NULL CHECK (frame_width BETWEEN 1 AND 3840),
            frame_height integer NOT NULL CHECK (frame_height BETWEEN 1 AND 3840),
            face_x double precision NOT NULL CHECK (face_x >= 0 AND face_x <= 1),
            face_y double precision NOT NULL CHECK (face_y >= 0 AND face_y <= 1),
            face_width double precision NOT NULL CHECK (face_width > 0 AND face_width <= 1),
            face_height double precision NOT NULL CHECK (face_height > 0 AND face_height <= 1),
            CONSTRAINT ck_video_face_box_in_frame CHECK (face_x + face_width <= 1.00001 AND face_y + face_height <= 1.00001),
            CONSTRAINT ux_video_face_observation UNIQUE (batch_id, frame_ordinal, face_ordinal)
        );
        CREATE INDEX ix_video_face_observation_batch ON video_face_observations(batch_id, frame_ordinal, face_ordinal);

        CREATE TABLE video_face_suggestions (
            observation_id uuid NOT NULL REFERENCES video_face_observations (id) ON DELETE CASCADE,
            rank integer NOT NULL CHECK (rank BETWEEN 1 AND 3),
            person_id uuid NOT NULL REFERENCES people (id) ON DELETE RESTRICT,
            similarity double precision NOT NULL CHECK (similarity BETWEEN -1 AND 1),
            PRIMARY KEY (observation_id, rank),
            UNIQUE (observation_id, person_id)
        );

        CREATE TABLE video_face_review_actions (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            observation_id uuid NOT NULL REFERENCES video_face_observations (id) ON DELETE CASCADE,
            decision text NOT NULL CHECK (decision IN ('known', 'unknown', 'not-face', 'cannot-tell', 'clear')),
            person_id uuid NULL REFERENCES people (id) ON DELETE RESTRICT,
            actor text NOT NULL CHECK (char_length(btrim(actor)) BETWEEN 1 AND 120),
            created_at_utc timestamptz NOT NULL,
            CONSTRAINT ck_video_face_review_identity CHECK (
                (decision='known' AND person_id IS NOT NULL)
                OR (decision <> 'known' AND person_id IS NULL))
        );
        CREATE INDEX ix_video_face_review_latest
            ON video_face_review_actions(observation_id, id DESC);

        -- The source row is locked by writers before any insert or review
        -- action. Source-exclusion insertion holds the source FK key-share
        -- lock, which serializes against that row lock.
        CREATE OR REPLACE FUNCTION photo_identity_purge_video_face_review_exclusion()
        RETURNS trigger LANGUAGE plpgsql AS $video_face_purge$
        BEGIN
            DELETE FROM video_face_evidence_batches b
            USING asset_revisions r, assets a
            WHERE b.asset_revision_id=r.id AND r.asset_id=a.id
              AND a.source_id=NEW.source_id AND a.source_key=NEW.source_key;
            RETURN NEW;
        END;
        $video_face_purge$;
        CREATE TRIGGER trg_source_exclusion_purge_video_face_review
            AFTER INSERT ON source_copy_exclusions FOR EACH ROW
            EXECUTE FUNCTION photo_identity_purge_video_face_review_exclusion();
        """;
}
