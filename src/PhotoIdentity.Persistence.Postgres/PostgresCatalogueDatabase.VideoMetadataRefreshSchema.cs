namespace PhotoIdentity.Persistence.Postgres;

/// <summary>
/// WI-0212 v41: append-only provenance for explicit metadata-only reinspection
/// of already-catalogued videos. Does not modify immutable source revisions,
/// original inspection profile or any photo/face/manual annotation history.
/// </summary>
public sealed partial class PostgresCatalogueDatabase
{
    private const string VideoMetadataRefreshSchemaMigration = """
        CREATE TABLE video_metadata_refresh_actions (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            asset_revision_id uuid NOT NULL REFERENCES video_revision_metadata(asset_revision_id)
                ON DELETE CASCADE,
            inspected_at_utc timestamp with time zone NOT NULL,
            tool_sha256 text NOT NULL
                CHECK (tool_sha256 ~ '^[0-9a-f]{64}$'),
            inspection_profile_id text NOT NULL
                CHECK (char_length(inspection_profile_id) BETWEEN 1 AND 100),
            changed_fields text NOT NULL
                CHECK (char_length(changed_fields) BETWEEN 1 AND 180),
            CONSTRAINT ck_video_metadata_refresh_approved_fields
                CHECK (changed_fields ~ '^(camera_make|camera_model|video_bitrate_bps|audio_sample_rate_hz|audio_channels|audio_channel_layout)(,(camera_make|camera_model|video_bitrate_bps|audio_sample_rate_hz|audio_channels|audio_channel_layout))*$')
        );
        CREATE INDEX ix_video_metadata_refresh_revision
            ON video_metadata_refresh_actions(asset_revision_id, id DESC);
        """;
}
