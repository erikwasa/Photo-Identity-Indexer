namespace PhotoIdentity.Persistence.Postgres;

/// <summary>
/// WI-0212: video-only, revision-bound manual metadata and presence. These
/// are deliberately not photo actions, face evidence or collection membership.
/// Source exclusions purge private annotations and annotations cannot apply
/// to non-video revisions at the database level.
/// </summary>
public sealed partial class PostgresCatalogueDatabase
{
    private const string VideoDetailsSchemaMigration = """
        CREATE TABLE video_capture_date_actions (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            asset_revision_id uuid NOT NULL,
            media_kind text NOT NULL DEFAULT 'video' CHECK (media_kind = 'video'),
            action_kind text NOT NULL CHECK (action_kind IN ('set', 'clear')),
            captured_at_utc timestamptz NULL,
            actor text NOT NULL CHECK (char_length(btrim(actor)) BETWEEN 1 AND 120),
            created_at_utc timestamptz NOT NULL,
            CONSTRAINT fk_video_date_revision FOREIGN KEY (asset_revision_id, media_kind)
              REFERENCES asset_revisions (id, media_kind) ON DELETE CASCADE,
            CONSTRAINT ck_video_date_action CHECK (
                (action_kind = 'set' AND captured_at_utc IS NOT NULL)
                OR (action_kind = 'clear' AND captured_at_utc IS NULL))
        );
        CREATE INDEX ix_video_date_revision
            ON video_capture_date_actions (asset_revision_id, id DESC);

        CREATE TABLE video_person_actions (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            asset_revision_id uuid NOT NULL,
            media_kind text NOT NULL DEFAULT 'video' CHECK (media_kind = 'video'),
            person_id uuid NOT NULL REFERENCES people (id) ON DELETE RESTRICT,
            action_kind text NOT NULL CHECK (action_kind IN ('add', 'remove')),
            actor text NOT NULL CHECK (char_length(btrim(actor)) BETWEEN 1 AND 120),
            created_at_utc timestamptz NOT NULL,
            CONSTRAINT fk_video_person_revision FOREIGN KEY (asset_revision_id, media_kind)
              REFERENCES asset_revisions (id, media_kind) ON DELETE CASCADE
        );
        CREATE INDEX ix_video_person_revision
            ON video_person_actions (asset_revision_id, person_id, id DESC);
        CREATE INDEX ix_video_person_person
            ON video_person_actions (person_id, asset_revision_id, id DESC);

        CREATE TABLE video_place_actions (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            asset_revision_id uuid NOT NULL,
            media_kind text NOT NULL DEFAULT 'video' CHECK (media_kind = 'video'),
            tag_id bigint NULL REFERENCES photo_tags (id) ON DELETE RESTRICT,
            action_kind text NOT NULL CHECK (action_kind IN ('set', 'clear')),
            source_kind text NOT NULL CHECK (source_kind IN ('manual', 'automatic')),
            provider text NULL,
            actor text NOT NULL CHECK (char_length(btrim(actor)) BETWEEN 1 AND 120),
            created_at_utc timestamptz NOT NULL,
            CONSTRAINT fk_video_place_revision FOREIGN KEY (asset_revision_id, media_kind)
              REFERENCES asset_revisions (id, media_kind) ON DELETE CASCADE,
            CONSTRAINT ck_video_place_action CHECK (
                (action_kind = 'set' AND tag_id IS NOT NULL)
                OR (action_kind = 'clear' AND tag_id IS NULL))
        );
        CREATE INDEX ix_video_place_revision
            ON video_place_actions (asset_revision_id, id DESC);

        -- Excluded sources must not retain private manual video annotations.
        -- Editors serialize on the sources row, as does exclusion insertion.
        CREATE OR REPLACE FUNCTION photo_identity_purge_video_details_exclusion()
        RETURNS trigger LANGUAGE plpgsql AS $video_details_purge$
        BEGIN
            DELETE FROM video_capture_date_actions action
              USING asset_revisions revision, assets asset
              WHERE action.asset_revision_id = revision.id AND revision.asset_id = asset.id
                AND asset.source_id = NEW.source_id AND asset.source_key = NEW.source_key;
            DELETE FROM video_place_actions action
              USING asset_revisions revision, assets asset
              WHERE action.asset_revision_id = revision.id AND revision.asset_id = asset.id
                AND asset.source_id = NEW.source_id AND asset.source_key = NEW.source_key;
            DELETE FROM video_person_actions action
              USING asset_revisions revision, assets asset
              WHERE action.asset_revision_id = revision.id AND revision.asset_id = asset.id
                AND asset.source_id = NEW.source_id AND asset.source_key = NEW.source_key;
            RETURN NEW;
        END;
        $video_details_purge$;
        CREATE TRIGGER trg_source_exclusion_purge_video_details
          AFTER INSERT ON source_copy_exclusions FOR EACH ROW
          EXECUTE FUNCTION photo_identity_purge_video_details_exclusion();
        """;
}
