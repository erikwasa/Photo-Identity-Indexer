#!/usr/bin/env python3
"""WI-0193 single TOPIQ held-out study: sealed preflight and separately gated run.

Preflight inspects benchmark partition membership but NEVER human ratings in
held-out/challenge rows. Evaluation requires a separate, private maintainer
authorization artifact NOT generated by this program. Evaluation consumes its
local one-shot claim before reading held-out human ratings. No inference,
images, network, catalogue writes, ranking integration or exclusion.
"""
from __future__ import annotations

import argparse
from collections import Counter
import itertools
import json
import math
import os
from pathlib import Path
import random

from calibration_policy_draft import fingerprint
from candidate_audit import LEVELS, load
from learned_iqa import private_output
from ranking_freeze import CRITERIA, THRESHOLD, freeze

PREFLIGHT_PROTOCOL = "wi0193-heldout-ranking-preflight-v1"
AUTH_PROTOCOL = "wi0193-heldout-one-shot-authorization-v1"
EVALUATION_PROTOCOL = "wi0193-heldout-ranking-one-shot-v1"
APPROVAL_TEXT = "I explicitly authorize the one-time WI-0193 TOPIQ held-out research evaluation."
CLAIM_FILENAME = "wi0193-heldout-once-claim.json"
HELDOUT_PHOTOS = 160
BENCHMARK_PHOTOS = 600
BOOTSTRAP_REPETITIONS = 1000
BOOTSTRAP_SEED = 20261018


def preflight(benchmark, scores, proposal, attestation):
    """Validate frozen research inputs without reading held-out human labels."""
    reference = freeze(proposal, benchmark, scores)
    if attestation != reference:
        raise ValueError("Private frozen attestation differs from calibrated evidence")
    if (attestation["researchHypothesisFrozen"] is not True
            or attestation["heldOutEvaluationAllowed"] is not False
            or attestation["heldOutLabelsAccessed"] is not False
            or attestation["productionModelApproved"] is not False
            or attestation["automaticVeryLowExclusionApproved"] is not False
            or attestation["researchCriteria"] != CRITERIA
            or attestation["fixedScoreGapThreshold"] != THRESHOLD):
        raise ValueError("Research freeze/permissions are inconsistent")

    photos = benchmark["photos"]
    if len(photos) != BENCHMARK_PHOTOS:
        raise ValueError("Unexpected benchmark population")
    partitions = Counter((p.get("partition"), p.get("sampleKind")) for p in photos)
    if partitions != Counter({
        ("calibration", "representative"): 240,
        ("held-out", "representative"): HELDOUT_PHOTOS,
        ("challenge", "challenge"): 200,
    }):
        raise ValueError("Frozen partition/sample-kind membership counts changed")
    ids = [p["revisionId"].casefold() for p in photos]
    if len(set(ids)) != BENCHMARK_PHOTOS:
        raise ValueError("Duplicate photo revisions")
    heldout_ids = sorted(p["revisionId"].casefold() for p in photos
                         if p["partition"] == "held-out"
                         and p["sampleKind"] == "representative")
    # Intentionally DO NOT inspect p["review"] here.
    return {
        "schemaVersion": 1,
        "protocol": PREFLIGHT_PROTOCOL,
        "status": "sealed-preflight-not-authorized",
        "benchmarkId": attestation["benchmarkId"],
        "frozenAttestationSha256": fingerprint(attestation),
        "calibrationReviewSha256": attestation["calibrationReviewSha256"],
        "scoreExportSha256": attestation["scoreExportSha256"],
        "heldOutCohortSha256": fingerprint(heldout_ids),
        "heldOutRepresentativePhotos": HELDOUT_PHOTOS,
        "totalBenchmarkPhotos": BENCHMARK_PHOTOS,
        "candidateId": attestation["candidateId"],
        "fixedScoreGapThreshold": THRESHOLD,
        "researchCriteria": dict(CRITERIA),
        "researchHypothesisFrozen": True,
        "heldOutEvaluationAllowed": False,
        "heldOutLabelsAccessed": False,
        "productionModelApproved": False,
        "automaticVeryLowExclusionApproved": False,
    }


def authorized(record, sealed_preflight):
    """Require separate exact-match explicit operator permission; never infer it."""
    if not isinstance(record, dict) or set(record) != {
            "schemaVersion", "protocol", "status", "preflightSha256",
            "approvalText", "oneTimeHeldOutEvaluationApproved",
            "productionModelApproved", "automaticVeryLowExclusionApproved"}:
        raise ValueError("A separate, strictly scoped authorization file is required")
    if (type(record["schemaVersion"]) is not int or record["schemaVersion"] != 1
            or record["protocol"] != AUTH_PROTOCOL
            or record["status"] != "explicit-maintainer-held-out-approval"
            or record["preflightSha256"] != fingerprint(sealed_preflight)
            or record["approvalText"] != APPROVAL_TEXT
            or record["oneTimeHeldOutEvaluationApproved"] is not True
            or record["productionModelApproved"] is not False
            or record["automaticVeryLowExclusionApproved"] is not False):
        raise ValueError("Maintainer authorization is missing or does not match the sealed preflight")


def selected_photos(benchmark, scores):
    """Only call AFTER authorization and the durable one-time claim exist."""
    score_lookup = {s["revisionId"].casefold(): s["rawScore"]
                    for s in scores["scores"]}
    selected = []
    for photo in benchmark["photos"]:
        if photo["partition"] != "held-out" or photo["sampleKind"] != "representative":
            continue
        quality = photo.get("review", {}).get("qualityLevel")
        if quality not in LEVELS and quality not in (None, "", "unsure"):
            raise ValueError("Invalid held-out review level")
        value = score_lookup[photo["revisionId"].casefold()]
        if type(value) not in (float, int) or not math.isfinite(value):
            raise ValueError("Held-out candidate score absent or invalid")
        selected.append((float(value), LEVELS.get(quality)))
    if len(selected) != HELDOUT_PHOTOS:
        raise ValueError("Wrong held-out sample count")
    return selected


def count_pairs(rows, weights=None):
    """Weighted all-pairs U-statistic. No pseudo-independent pair resampling."""
    if weights is None:
        weights = [1] * len(rows)
    if len(rows) != len(weights):
        raise ValueError("Unexpected bootstrap weight vector")
    keys = ("allPairs", "selectedPairs", "abstainedPairs",
            "knownTierPairs", "unknownTierPairs",
            "sameTierPairs", "selectedSameTierPairs",
            "differentTierPairs", "selectedDifferentTierPairs",
            "correctDifferentTierPairs", "twoOrMoreTierPairs",
            "selectedTwoOrMoreTierPairs", "correctTwoOrMoreTierPairs")
    counts = dict.fromkeys(keys, 0)
    for i in range(len(rows)):
        a_score, a_tier = rows[i]
        for j in range(i + 1, len(rows)):
            weight = weights[i] * weights[j]
            if not weight:
                continue
            b_score, b_tier = rows[j]
            counts["allPairs"] += weight
            gap = abs(a_score - b_score)
            chosen = gap > 0 and gap >= THRESHOLD
            counts["selectedPairs" if chosen else "abstainedPairs"] += weight
            if a_tier is None or b_tier is None:
                counts["unknownTierPairs"] += weight
                continue
            counts["knownTierPairs"] += weight
            if a_tier == b_tier:
                counts["sameTierPairs"] += weight
                if chosen:
                    counts["selectedSameTierPairs"] += weight
                continue
            counts["differentTierPairs"] += weight
            delta_tier = abs(a_tier - b_tier)
            if delta_tier >= 2:
                counts["twoOrMoreTierPairs"] += weight
            if chosen:
                counts["selectedDifferentTierPairs"] += weight
                correct = (a_score - b_score) * (a_tier - b_tier) > 0
                if correct:
                    counts["correctDifferentTierPairs"] += weight
                if delta_tier >= 2:
                    counts["selectedTwoOrMoreTierPairs"] += weight
                    if correct:
                        counts["correctTwoOrMoreTierPairs"] += weight
    return counts


def metrics(c):
    def safe(numerator, denominator):
        return c[numerator] / c[denominator] if c[denominator] else None
    return {
        "allPairDecisionCoverage": safe("selectedPairs", "allPairs"),
        "differentTierOrderingAccuracy": safe(
            "correctDifferentTierPairs", "selectedDifferentTierPairs"),
        "twoOrMoreTierOrderingAccuracy": safe(
            "correctTwoOrMoreTierPairs", "selectedTwoOrMoreTierPairs"),
        "differentTierDecisionCoverage": safe(
            "selectedDifferentTierPairs", "differentTierPairs"),
        "twoOrMoreTierDecisionCoverage": safe(
            "selectedTwoOrMoreTierPairs", "twoOrMoreTierPairs"),
        "sameTierDecisionRate": safe(
            "selectedSameTierPairs", "sameTierPairs"),
    }


def research_decision(c, m):
    checks = {
        "differentTierSelectedOrderingAtLeast80Percent": (
            c["selectedDifferentTierPairs"] > 0
            and m["differentTierOrderingAccuracy"] >= CRITERIA[
                "minimumDifferentTierSelectedAccuracy"]),
        "allPairDecisionCoverageAtLeast20Percent": (
            m["allPairDecisionCoverage"] is not None
            and m["allPairDecisionCoverage"] >= CRITERIA[
                "minimumAllPairDecisionCoverage"]),
        "twoOrMoreTierSelectedOrderingAtLeast80Percent": (
            c["selectedTwoOrMoreTierPairs"] > 0
            and m["twoOrMoreTierOrderingAccuracy"] >= CRITERIA[
                "minimumTwoOrMoreTierSelectedAccuracy"]),
    }
    return {"checks": checks, "allResearchCriteriaMet": all(checks.values())}


def _interval(samples):
    if not samples:
        return None
    values = sorted(samples)
    # Defined, deterministic nearest-rank 2.5 and 97.5 percentiles.
    return [values[max(0, math.ceil(.025 * len(values)) - 1)],
            values[max(0, math.ceil(.975 * len(values)) - 1)]]


def photo_bootstrap(rows, repetitions=BOOTSTRAP_REPETITIONS, seed=BOOTSTRAP_SEED):
    if type(repetitions) is not int or not 1 <= repetitions <= 5000:
        raise ValueError("Invalid bootstrap repetitions")
    rnd = random.Random(seed)
    names = ("allPairDecisionCoverage", "differentTierOrderingAccuracy",
             "twoOrMoreTierOrderingAccuracy")
    series = {name: [] for name in names}
    n = len(rows)
    for _ in range(repetitions):
        # Resample photos, not pairs. Count only pairs of *distinct originals*
        # with product multiplicities. Repeated appearances of one original
        # never become artificial self-comparisons.
        multiplicities = Counter(rnd.randrange(n) for _ in range(n))
        weights = [multiplicities.get(i, 0) for i in range(n)]
        result = metrics(count_pairs(rows, weights))
        for name in names:
            if result[name] is not None:
                series[name].append(result[name])
    return {
        "method": "photo-cluster-bootstrap-with-replacement; distinct-original pairs weighted by multiplicity product",
        "repetitions": repetitions,
        "seed": seed,
        "intervalPercent": 95,
        "percentiles": "nearest-rank-2.5-and-97.5",
        "endpoints": {key: {
            "interval": _interval(series[key]),
            "definedReplicates": len(series[key]),
            "undefinedReplicates": repetitions - len(series[key]),
        } for key in names},
    }


def heldout_report(rows, sealed_preflight):
    counts = count_pairs(rows)
    metric_values = metrics(counts)
    return {
        "schemaVersion": 1,
        "protocol": EVALUATION_PROTOCOL,
        "status": "held-out-research-evaluated-once",
        "candidateId": sealed_preflight["candidateId"],
        "fixedScoreGapThreshold": THRESHOLD,
        "representativeHeldOutPhotos": len(rows),
        "knownTierHeldOutPhotos": sum(tier is not None for _, tier in rows),
        "unsureOrUnratedHeldOutPhotos": sum(tier is None for _, tier in rows),
        "inferenceFailures": 0,
        "counts": counts,
        "metrics": metric_values,
        "researchDecision": research_decision(counts, metric_values),
        "photoResampledUncertainty": photo_bootstrap(rows),
        "heldOutEvaluationAllowedForThisOneTimeRun": True,
        "heldOutEvaluatedOnce": True,
        "productionModelApproved": False,
        "automaticVeryLowExclusionApproved": False,
        "interpretation": (
            "Research-only one-time held-out test. Earlier candidate/quantile "
            "selection used calibration exploration. Not a five-tier rating, "
            "slideshow ranker, exclusion policy or deployment license."
        ),
    }


def _private_new_json(path, data):
    target = private_output(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("x", encoding="utf-8") as handle:
        json.dump(data, handle, indent=2, allow_nan=False)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())


def consume_once_claim(attestation_path, sealed_preflight, authorization):
    """Irreversible-by-default file reservation BEFORE opening human ratings."""
    frozen_path = Path(attestation_path).resolve(strict=True)
    claim = frozen_path.with_name(CLAIM_FILENAME)
    _private_new_json(str(claim), {
        "schemaVersion": 1,
        "protocol": EVALUATION_PROTOCOL,
        "status": "one-time-held-out-access-claimed",
        "frozenAttestationSha256": sealed_preflight["frozenAttestationSha256"],
        "preflightSha256": fingerprint(sealed_preflight),
        "authorizationSha256": fingerprint(authorization),
        "note": "Do not delete/retry if a later evaluation step fails. Investigate first.",
    })


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=("preflight", "evaluate"), required=True)
    parser.add_argument("--proposal", required=True)
    parser.add_argument("--frozen", required=True)
    parser.add_argument("--input", required=True)
    parser.add_argument("--scores", required=True)
    parser.add_argument("--preflight", help="Pre-existing private preflight record, only for evaluate")
    parser.add_argument("--authorization", help="Separate private operator approval, only for evaluate")
    parser.add_argument("--output", required=True, help="New private JSON, never overwrite")
    args = parser.parse_args()

    if args.mode == "preflight":
        if args.authorization or args.preflight:
            parser.error("Preflight must not include evaluation authorization")
    elif not args.authorization or not args.preflight:
        parser.error("Held-out evaluation requires separate preflight and authorization")

    # This load holds the manifest as data, but ONLY preflight() examines it
    # prior to authorization; that function never accesses held-out reviews.
    benchmark = load(args.input)
    scores = load(args.scores)
    proposal = load(args.proposal)
    frozen = load(args.frozen)
    verified = preflight(benchmark, scores, proposal, frozen)

    if args.mode == "preflight":
        _private_new_json(args.output, verified)
        print(json.dumps({
            "protocol": PREFLIGHT_PROTOCOL, "status": verified["status"],
            "candidate": verified["candidateId"],
            "threshold": verified["fixedScoreGapThreshold"],
            "heldOutRepresentativePhotos": verified["heldOutRepresentativePhotos"],
            "heldOutEvaluationAllowed": False,
            "heldOutLabelsAccessed": False,
        }, indent=2))
        return

    sealed_preflight = load(args.preflight)
    if sealed_preflight != verified:
        raise ValueError("Private sealed preflight changed; evaluation refused")
    authorization = load(args.authorization)
    authorized(authorization, sealed_preflight)
    # Fail before consuming the one-shot claim when output exists, and refuse
    # output paths colliding with any input or the one-shot marker.
    output = private_output(args.output)
    forbidden = [args.input, args.scores, args.proposal, args.frozen,
                 args.preflight, args.authorization,
                 str(Path(args.frozen).resolve().with_name(CLAIM_FILENAME))]
    if output in [Path(p).resolve() for p in forbidden]:
        raise ValueError("Evaluation output overlaps a private input or claim")
    consume_once_claim(args.frozen, sealed_preflight, authorization)
    # Access to the formerly sealed held-out human reviews starts HERE only.
    rows = selected_photos(benchmark, scores)
    report = heldout_report(rows, verified)
    _private_new_json(args.output, report)
    # Only aggregate metrics, never photo IDs, tiers/labels, paths or hashes.
    print(json.dumps(report, indent=2, allow_nan=False))


if __name__ == "__main__":
    main()
